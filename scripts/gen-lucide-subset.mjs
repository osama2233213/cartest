/**
 * Builds src/lib/lucide-subset.ts: only the lucide icons this app uses, each from its own file.
 * The dev server then downloads a few KB of icons instead of the whole 3.9 MB library.
 * Run after adding an icon:  npm run icons
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "src");
const OUT = join(src, "lib", "lucide-subset.ts");

const walk = (dir) =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : /\.(tsx?|jsx?)$/.test(f) && p !== OUT ? [p] : [];
  });

/** Every name imported from "lucide-react" anywhere in src (values only, not `type` imports). */
export function usedIcons() {
  const names = new Set();
  const re = /import\s+(?:type\s+)?\{([^}]*)\}\s+from\s+["']lucide-react["']/g;
  for (const file of walk(src)) {
    const text = readFileSync(file, "utf8");
    for (const m of text.matchAll(re)) {
      if (/^import\s+type/.test(m[0])) continue;
      for (const part of m[1].split(",")) {
        const t = part.trim();
        if (!t || t.startsWith("type ")) continue;
        names.add(t.split(/\s+as\s+/)[0].trim());
      }
    }
  }
  return [...names].sort();
}

// The main file lists every name an icon answers to (CheckCircle2, CircleCheck, ...), each pointing at one icon file.
const index = readFileSync(join(root, "node_modules", "lucide-react", "dist", "esm", "lucide-react.js"), "utf8");
const fileOf = new Map();
for (const m of index.matchAll(/export \{([^}]*)\} from '\.\/icons\/([^']+)\.js';/g)) {
  for (const n of m[1].matchAll(/default as (\w+)/g)) fileOf.set(n[1], m[2]);
}

const icons = usedIcons();
const missing = icons.filter((n) => !fileOf.has(n));
if (missing.length) {
  console.error(`Not found in lucide-react: ${missing.join(", ")}`);
  process.exit(1);
}

// Each icon file is just a name and some path data. Copy that into one file, so the browser fetches one small module
// instead of 100 separate ones (or the whole 3.9 MB library).
const iconsDir = join(root, "node_modules", "lucide-react", "dist", "esm", "icons");
const definitions = new Map(); // icon file -> [lucide name, path data]
const define = (file) => {
  if (!definitions.has(file)) {
    const text = readFileSync(join(iconsDir, `${file}.js`), "utf8");
    const node = /const __iconNode = (\[[\s\S]*?\]);\nconst \w+ = createLucideIcon\("([^"]+)"/.exec(text);
    if (!node) {
      console.error(`Could not read icon file ${file}.js`);
      process.exit(1);
    }
    definitions.set(file, [node[2], node[1]]);
  }
};
icons.forEach((n) => define(fileOf.get(n)));
const varOf = (file) => `icon_${file.replace(/[^a-z0-9]/gi, "_")}`;

const lines = [
  // The rest of the app is type-checked against the real "lucide-react" package; this file only has to run.
  "// @ts-nocheck",
  "// Generated by scripts/gen-lucide-subset.mjs. Do not edit by hand. Run `npm run icons` after adding an icon.",
  "// Only the icons this app uses, in one small file, so the dev server doesn't download all of lucide-react.",
  'import createLucideIcon from "lucide-react/dist/esm/createLucideIcon.js";',
  "",
  ...[...definitions].map(([file, [name, data]]) => `const ${varOf(file)} = createLucideIcon(${JSON.stringify(name)}, ${data});`),
  "",
  `export { ${icons.map((n) => `${varOf(fileOf.get(n))} as ${n}`).join(", ")} };`,
  "export { createLucideIcon };",
  "",
];
writeFileSync(OUT, lines.join("\n"));
console.log(`lucide-subset.ts: ${icons.length} icons`);
